"""Record the web app's fixture from the real API.

Starts its own replay server (no network, no key), plays the demo scenes with the kitchen's
fixed agent and saves every /api answer the web app reads, once per demo state:
the mozzarella request (none, waiting, placed, rejected) times the steady order (pending,
renewed, one line or both accepted), into src/lib/api/snapshots/states.ts. The scene files next to it (from
scripts/snapshot_api.py) hold the end of each scene; this one also holds the states in between that
the pages click through, such as the mozzarella order waiting for the owner.
The mock in src/lib/api/mock.ts serves this file and nothing else.

    cd validio/src/backend && uv run python ../frontend/scripts/snapshots.py
"""

import asyncio
import json
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
from demo_check import Run, env, start_server  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "src" / "lib" / "api" / "snapshots" / "states.ts"
GROUPS = {  # path prefix -> (group, type of one answer)
    "/api/inbox": ("inbox", "InboxItem[]"), "/api/requests/": ("requests", "SupplyRequest"),
    "/api/orders/": ("orders", "Order"), "/api/spend-passes/": ("spendPass", "SpendPass"),
    "/api/ledger": ("ledger", "Ledger"), "/api/steady/": ("steady", "SteadyOrder"),
    "/api/steady": ("steadyList", "SteadyOrderSummary[]"), "/api/demo": ("demo", "DemoState"),
}
HEAD = """// Generated by scripts/snapshots.py from the real backend. Do not edit.
// Every distinct /api answer once, and per demo state which one each path serves.
// Typed against types.ts, so `npm run check` fails when backend and pages drift apart.

import type {
  DemoState, InboxItem, Ledger, Order, SpendPass, SteadyOrder, SteadyOrderSummary, SupplyRequest,
} from "../types";

export interface Answers {
  inbox: InboxItem[][];
  requests: Record<string, SupplyRequest[]>;
  orders: Record<string, Order[]>;
  spendPass: Record<string, SpendPass[]>;
  ledger: Ledger[];
  steady: Record<string, SteadyOrder[]>;
  steadyList: SteadyOrderSummary[][];
  demo: DemoState[];
}

"""
MOZ = ["none", "waiting", "placed", "rejected"]
STEADY = ["pending", "renewed", "accepted", "mozzarella", "both"]  # accepted: the pancakes
PORT = 8437
# the same refusal as scripts/snapshot_api.py: no token, presentation, key or approver list
SECRET = re.compile(r'eyJ[A-Za-z0-9_-]{10,}\.|~eyJ|"d"\s*:\s*"|"issuance"|VALIO_API_KEY|owner:anna')


def capture(run: Run) -> dict:
    got: dict = {}
    for path in ("/api/inbox", "/api/spend-passes/M-1", "/api/ledger", "/api/steady", "/api/steady/S-1", "/api/demo"):
        got[path] = run.get(path)
    for item in got["/api/inbox"]:
        req = run.get(f"/api/requests/{item['id']}")
        got[f"/api/requests/{item['id']}"] = req
        if req.get("orderId"):
            got[f"/api/orders/{req['orderId']}"] = run.get(f"/api/orders/{req['orderId']}")
    return got


async def one(base, db, keys, token, code, moz: str, steady: str) -> dict:
    run = Run(base, db, keys, token, code, False)
    run.demo("reset")
    await run.agent(1)
    await run.agent(2)
    if moz != "none":
        run.demo("stock-out")
        _, a = await run.agent(3)
        oid = run.get(f"/api/requests/{a['request_supply']['id']}")["orderId"]
        if moz in ("placed", "rejected"):
            act = "approve" if moz == "placed" else "reject"
            run.post(f"/api/orders/{oid}/{act}", json={"code": code})
    chef = {"X-Approve-Code": code}  # renew and accept need the code too
    if steady != "pending":
        run.post("/api/steady/S-1/renew", headers=chef)
        if steady in ("accepted", "both"):
            run.post("/api/steady/S-1/lines/471376/accept", headers=chef)
        if steady in ("mozzarella", "both"):
            r = run.http.post("/api/steady/S-1/lines/466375/accept", headers=chef)
            if r.status_code != 200:  # out of stock after the stock-out: the mock answers the same
                return {"refused": r.json()["detail"]}
    return capture(run)


async def main() -> int:
    keys = Path(env().get("VALIDIO_KEYS") or ROOT / "data" / "keys")
    store = ROOT / "artifacts" / "snapshots"
    store.mkdir(parents=True, exist_ok=True)
    token, code = secrets.token_urlsafe(16), f"{secrets.randbelow(10**6):06d}"
    proc = start_server(PORT, store, token, code)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    seen: dict[str, list[str]] = {}
    states: dict[str, dict[str, int]] = {}
    refused: dict[str, str] = {}
    try:
        for moz in MOZ:
            for steady in STEADY:
                data = await one(f"http://127.0.0.1:{PORT}", store / "validio.db", keys, token, code, moz, steady)
                if "refused" in data:
                    refused[f"{moz}-{steady}"] = data["refused"]
                    print(f"{moz}-{steady}: refused")
                    continue
                pick = states[f"{moz}-{steady}"] = {}
                for path, answer in data.items():
                    text = json.dumps(answer, sort_keys=True, ensure_ascii=False)
                    known = seen.setdefault(path, [])
                    if text not in known:
                        known.append(text)
                    pick[path] = known.index(text)
                print(f"{moz}-{steady}: {len(data)} answers")
    finally:
        proc.terminate()
        proc.wait(10)
    answers: dict = {}
    for path, texts in sorted(seen.items()):
        prefix = max((k for k in GROUPS if path == k or (k.endswith("/") and path.startswith(k))), key=len)
        group, _ = GROUPS[prefix]
        items = [json.loads(t) for t in texts]
        if prefix.endswith("/"):
            answers.setdefault(group, {})[path[len(prefix):]] = items
        else:
            answers[group] = items
    text = json.dumps(answers)
    if SECRET.search(text):
        raise SystemExit(f"refused: a snapshot holds {SECRET.search(text).group(0)[:12]}...")
    dump = lambda v: json.dumps(v, ensure_ascii=False, sort_keys=True, indent=1)  # noqa: E731
    OUT.write_text(HEAD + f"export const answers: Answers = {dump(answers)};\n\n"
                   f"export const states: Record<string, Record<string, number>> = {dump(states)};\n\n"
                   f"/** States the real backend refused to reach, with its answer. */\n"
                   f"export const refused: Record<string, string> = {dump(refused)};\n")
    print(f"wrote {OUT.name}: {sum(len(v) for v in seen.values())} distinct answers")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
