"""`make snapshots`: the web app's API contract, recorded from the real backend.

Runs the demo scenes the way `make demo-check` does (own server on 127.0.0.1, replayed Valio answers,
no network) and after each scene saves every /api answer the web app reads into
src/frontend/src/lib/api/snapshots/sceneN.json. It also writes contract.ts there, which assigns each
snapshot to the types in types.ts, so `npm run check` fails when backend and frontend drift apart.

Only what the API already returns to the kitchen lands there. A snapshot that holds a Spend Pass
issuance, a presentation or a key is refused.
"""

import asyncio
import json
import re
import secrets
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from demo_check import ROOT, Fail, Run, env, free_port, start_server

OUT = ROOT / "src" / "frontend" / "src" / "lib" / "api" / "snapshots"
PORT = free_port()  # never another lane's server
# the approve code is not checked here: six random digits turn up in hashes by chance
# a JWS or SD-JWT (eyJ...), an SD-JWT disclosure chain, a JWK private part
SECRET = re.compile(r'eyJ[A-Za-z0-9_-]{10,}\.|~eyJ|"d"\s*:\s*"|"issuance"|"VALIO_API_KEY')

TYPES = {"inbox": "InboxItem[]", "requests": "Record<string, SupplyRequest>", "spendPass": "SpendPass",
         "orders": "Record<string, Order>", "ledger": "Ledger", "steadyList": "SteadyOrderSummary[]",
         "steady": "Record<string, SteadyOrder>", "demo": "DemoState"}


def collect(run: Run) -> dict:
    inbox = run.get("/api/inbox")
    requests = {i["id"]: run.get(f"/api/requests/{i['id']}") for i in inbox}
    orders = {r["orderId"]: run.get(f"/api/orders/{r['orderId']}") for r in requests.values() if r.get("orderId")}
    snap = {"inbox": inbox, "requests": requests}
    sp = run.http.get("/api/spend-passes/M-1")
    if sp.status_code == 200:
        snap["spendPass"] = sp.json()
    steady_list = run.get("/api/steady")
    snap |= {"orders": orders, "ledger": run.get("/api/ledger"), "steadyList": steady_list,
             "steady": {s["id"]: run.get(f"/api/steady/{s['id']}") for s in steady_list},
             "demo": run.get("/api/demo")}
    return snap


def contract_ts(scenes: list[int]) -> str:
    fields = "\n".join(f"  {k}{'?' if k == 'spendPass' else ''}: {t};" for k, t in TYPES.items())
    out = ["// Generated by `make snapshots` (scripts/snapshot_api.py). Do not edit.",
           "// Every /api answer the web app reads, recorded from the real backend after each demo scene and",
           "// assigned to the hand-written types, so `npm run check` fails when the two drift apart.",
           "", 'import type {', "  DemoState,", "  InboxItem,", "  Ledger,", "  Order,", "  SpendPass,",
           "  SteadyOrder,", "  SteadyOrderSummary,", "  SupplyRequest,", '} from "../types";', "",
           "export interface Snapshot {", fields, "}", ""]
    for n in scenes:
        body = (OUT / f"scene{n}.json").read_text().rstrip()
        out += [f"export const scene{n}: Snapshot = {body};", ""]
    out.append(f"export const scenes = {{ {', '.join(f'scene{n}' for n in scenes)} }};")
    return "\n".join(out) + "\n"


async def main() -> int:
    scenes = [1, 2, 3, 4, 5]
    store = ROOT / "artifacts" / "snapshots"
    store.mkdir(parents=True, exist_ok=True)
    token, code = secrets.token_urlsafe(16), f"{secrets.randbelow(10**6):06d}"
    proc = start_server(PORT, store, token, code)
    OUT.mkdir(parents=True, exist_ok=True)
    try:
        run = Run(f"http://127.0.0.1:{PORT}", store / "validio.db", Path(env().get("VALIDIO_KEYS") or ROOT / "data" / "keys"), token, code, False)
        run.demo("reset")
        for n in scenes:
            print(f"  scene {n} OK: {await getattr(run, f'scene{n}')()}")
            text = json.dumps(collect(run), indent=2, ensure_ascii=False)
            if SECRET.search(text) or token in text:
                print(f"FAILED: the scene {n} snapshot holds a pass, a key or a secret")
                return 1
            (OUT / f"scene{n}.json").write_text(text + "\n")
    except Fail as e:
        print(f"FAILED: {e}")
        return 1
    finally:
        proc.terminate()
        proc.wait(10)
    (OUT / "contract.ts").write_text(contract_ts(scenes))
    print(f"wrote {len(scenes)} snapshots and contract.ts to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
